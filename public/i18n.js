export const STRINGS = S;
const LANG_KEY = "lfp.lang";
let lang = "ja";

export function detectLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved && S[saved]) return saved;
  } catch { /* ignore */ }
  const navs = (typeof navigator !== "undefined" && (navigator.languages?.length ? navigator.languages : [navigator.language])) || [];
  for (const n of navs) {
    const l = String(n || "").toLowerCase();
    if (l.startsWith("zh")) return /tw|hk|mo|hant/.test(l) ? "zh-Hant" : "zh-Hans";
    const base = l.split("-")[0];
    if (S[base]) return base;
  }
  return "en";
}

export function getLang() { return lang; }

export function setLang(code) {
  lang = S[code] ? code : "en";
  try { localStorage.setItem(LANG_KEY, lang); } catch { /* ignore */ }
  if (typeof document !== "undefined") document.documentElement.lang = lang === "zh-Hans" ? "zh-Hans" : lang === "zh-Hant" ? "zh-Hant" : lang;
  return lang;
}

export function has(key) { return key in (S[lang] || {}) || key in S.en; }

export function t(key, params) {
  let s = (S[lang] && S[lang][key]) ?? S.en[key] ?? S.ja[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

// data-i18n="key" → textContent、data-i18n-html="key" → innerHTML（辞書内の静的マークアップのみ）、
// data-i18n-placeholder / data-i18n-aria → 属性
export function applyTranslations(root = document) {
  for (const el of root.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll("[data-i18n-html]")) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of root.querySelectorAll("[data-i18n-placeholder]")) el.placeholder = t(el.dataset.i18nPlaceholder);
  for (const el of root.querySelectorAll("[data-i18n-aria]")) el.setAttribute("aria-label", t(el.dataset.i18nAria));
}
